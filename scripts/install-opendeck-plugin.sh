#!/usr/bin/env bash
# Install the Elgato plugin into OpenDeck on Linux, running from this checkout's venv.
# The manifest is elgato/'s with a Linux entry added, so the macOS plugins stay untouched.
# Override the folder with OPENDECK_PLUGINS_DIR.
#   scripts/install-opendeck-plugin.sh              install (or update)
#   scripts/install-opendeck-plugin.sh --uninstall  remove
. "$(dirname "$0")/_lib.sh"
require_os linux
use_venv
command -v jq >/dev/null || die "jq not found (pacman -S jq)"

dest_dir="${OPENDECK_PLUGINS_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/opendeck/plugins}"
dest="$dest_dir/com.herdr.dock.sdPlugin"
src="$ROOT/elgato/com.herdr.dock.sdPlugin"

if [ "${1:-}" = "--uninstall" ]; then
    rm -rf "$dest"
    log "removed $dest; restart OpenDeck"
    exit 0
fi
[ -d "$dest_dir" ] || die "plugin dir not found: $dest_dir (is OpenDeck installed and started once?)"

rm -rf "$dest"
mkdir -p "$dest"
cp -R "$src/static" "$src/pi" "$dest/"
# pi/agent.html: the per-key "Agent number" setting (only wired up here until tested on a Mac)
jq '.CodePathLin = "herdr-dock-plugin" | .OS += [{"Platform": "linux"}]
    | .Actions[0].PropertyInspectorPath = "pi/agent.html"' \
    "$src/manifest.json" >"$dest/manifest.json"
cat >"$dest/herdr-dock-plugin" <<EOF
#!/bin/sh
# Generated by scripts/install-opendeck-plugin.sh: runs the plugin from $ROOT.
cd "$ROOT" && exec "$VENV/bin/python" -m elgato.plugin_main "\$@"
EOF
chmod +x "$dest/herdr-dock-plugin"
log "installed to $dest"
log "restart OpenDeck; logs: OpenDeck's plugin log and herdr-dock's elgato-plugin.log"
